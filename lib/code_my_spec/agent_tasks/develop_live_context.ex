defmodule CodeMySpec.AgentTasks.DevelopLiveContext do
  @moduledoc """
  Container task for developing a live context through its requirement lifecycle.

  Used by the `/develop-liveview` skill (for live_context surface components) and
  as a task module for `:orchestrate` scope requirements. The heavy orchestration
  is handled by `ProjectCoordinator` via `default_orchestrate/4`.

  A live context is a spec-only grouping (no code file) containing LiveViews and
  LiveComponents. The parent live_context gets a spec but no implementation.

  `command/3` returns static development instructions.
  `evaluate/3` checks whether all children have their implementation requirements
  satisfied.
  """

  alias CodeMySpec.Components
  alias CodeMySpec.Components.ComponentRepository
  alias CodeMySpec.ProjectCoordinator

  @implementation_reqs [
    "spec_file",
    "spec_valid",
    "implementation_file",
    "test_file",
    "tests_passing"
  ]

  def command(_scope, session, _opts \\ []) do
    %{component: live_context} = session

    {:ok, """
    # Develop Live Context: #{live_context.name}

    Develop this live context through its requirement lifecycle.
    Invoke subagents for each prompt file generated by the orchestrator.

    ## Lifecycle Phases

    1. **Live Context Spec** - Define the grouping, list child views and components
    2. **Child Specs** - Design each child LiveView and LiveComponent
    3. **Implementation** - Tests + code for children only (LiveComponents first, then LiveViews)

    **Note:** The parent live context has no code file — only children are implemented.

    ## Subagent Usage

    - For spec prompts: `@"CodeMySpec:spec-writer (agent)"`
    - For test prompts: `@"CodeMySpec:test-writer (agent)"`
    - For code prompts: `@"CodeMySpec:code-writer (agent)"`

    ## Completion

    When all tasks are complete, **stop the session** so the hook can validate.
    """}
  end

  def evaluate(scope, session, _opts \\ []) do
    %{component: live_context} = session
    # Reload to ensure requirements are preloaded
    _live_context = ComponentRepository.get_component(scope, live_context.id)
    # Only check children — parent live_context has no code
    children = Components.list_child_components(scope, live_context.id)

    missing = Enum.reject(children, &all_requirements_satisfied?/1)

    if Enum.empty?(missing) do
      {:ok, :valid}
    else
      names = Enum.map_join(missing, "\n", fn c -> "- #{c.module_name}" end)
      {:ok, :invalid, "Children still need work:\n#{names}"}
    end
  end

  def orchestrate(scope, session, opts \\ []) do
    ProjectCoordinator.default_orchestrate(__MODULE__, scope, session, opts)
  end

  def orchestrate_evaluate(scope, session, opts \\ []) do
    ProjectCoordinator.default_orchestrate_evaluate(__MODULE__, scope, session, opts)
  end

  defp all_requirements_satisfied?(component) do
    reqs = component.requirements || []

    Enum.all?(@implementation_reqs, fn req_name ->
      not Enum.any?(reqs, fn r -> r.name == req_name and not r.satisfied end)
    end)
  end
end
