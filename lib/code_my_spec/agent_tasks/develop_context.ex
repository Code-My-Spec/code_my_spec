defmodule CodeMySpec.AgentTasks.DevelopContext do
  @moduledoc """
  Container task for developing a bounded context through its requirement lifecycle.

  Used by the `/develop` skill (`develop context`) and as a task module for
  `:orchestrate` scope requirements. Heavy orchestration lives in the
  requirements graph itself (children's code, then the context's) — this module provides the entry-point prompt and a lifecycle-completion
  check.

  `command/2` returns static development instructions naming the context.
  `evaluate/2` checks whether the context and all child components have
  their implementation requirements satisfied.
  """

  alias CodeMySpec.Components
  alias CodeMySpec.Components.ComponentRepository
  alias CodeMySpec.Requirements

  @implementation_reqs ["implementation_file"]

  def command(scope, task) do
    context = Components.get_component!(scope, task.component_id)

    {:ok,
     """
     # Develop Context: #{context.name}

     Develop this bounded context through its requirement lifecycle.
     Invoke subagents for each prompt file generated by the orchestrator.

     The context and its children are records: read them with
     `show_architecture_overview`. Build in dependency order — schemas first, then
     repositories, then services, the context module last.

     ## Subagent Usage

     - For code prompts: `@"CodeMySpec:code-writer (agent)"`

     ## Completion

     When all tasks are complete, **stop the session** so the hook can validate.
     """}
  end

  def evaluate(scope, task) do
    context = Components.get_component!(scope, task.component_id)
    context = ComponentRepository.get_component(scope, context.id)
    children = Components.list_child_components(scope, context.id)
    all = [context | children]

    missing = Enum.reject(all, &all_requirements_satisfied?(scope, &1))

    if Enum.empty?(missing) do
      {:ok, :valid}
    else
      names = Enum.map_join(missing, "\n", fn c -> "- #{c.module_name}" end)
      {:ok, :invalid, "Components still need work:\n#{names}"}
    end
  end

  def dispatch(_node) do
    "Implement a context — its schemas, repository and public interface — " <>
      "as its component record describes it. Use when its implementation " <>
      "file is missing."
  end

  defp all_requirements_satisfied?(scope, component) do
    reqs = Requirements.compute_component_requirements(scope, component)

    Enum.all?(@implementation_reqs, fn req_name ->
      not Enum.any?(reqs, fn r -> r.name == req_name and not r.satisfied end)
    end)
  end
end
