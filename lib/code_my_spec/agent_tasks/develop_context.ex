defmodule CodeMySpec.AgentTasks.DevelopContext do
  @moduledoc """
  Container task for developing a context through its requirement lifecycle.

  Used by the `/develop-context` skill and as a task module for `:orchestrate`
  scope requirements. The heavy orchestration (collecting descendants, finding
  actionable work, writing prompt files) is handled by `ProjectCoordinator`
  via `default_orchestrate/4`.

  `command/3` returns static development instructions.
  `evaluate/3` checks whether all components in the context tree have their
  implementation requirements satisfied.
  """

  alias CodeMySpec.Components
  alias CodeMySpec.Components.ComponentRepository
  alias CodeMySpec.ProjectCoordinator

  @implementation_reqs [
    "spec_file",
    "spec_valid",
    "children_designs",
    "review_file",
    "review_valid",
    "children_implementations",
    "implementation_file",
    "test_file",
    "tests_passing"
  ]

  def command(_scope, session, _opts \\ []) do
    %{component: context} = session

    {:ok, """
    # Develop Context: #{context.name}

    Develop this context through its requirement lifecycle.
    Invoke subagents for each prompt file generated by the orchestrator.

    ## Lifecycle Phases

    1. **Context Spec** - Define the bounded context architecture
    2. **Component Specs** - Design each child component
    3. **Design Review** - Validate architecture before implementation
    4. **Implementation** - Tests + code per component in dependency order

    ## Subagent Usage

    - For spec prompts: `@"CodeMySpec:spec-writer (agent)"`
    - For design review prompts: `@"CodeMySpec:spec-writer (agent)"`
    - For test prompts: `@"CodeMySpec:test-writer (agent)"`
    - For code prompts: `@"CodeMySpec:code-writer (agent)"`

    ## Completion

    When all tasks are complete, **stop the session** so the hook can validate.
    """}
  end

  def evaluate(scope, session, _opts \\ []) do
    %{component: context} = session
    context = ComponentRepository.get_component(scope, context.id)
    children = Components.list_child_components(scope, context.id)
    all = [context | children]

    missing = Enum.reject(all, &all_requirements_satisfied?/1)

    if Enum.empty?(missing) do
      {:ok, :valid}
    else
      names = Enum.map_join(missing, "\n", fn c -> "- #{c.module_name}" end)
      {:ok, :invalid, "Components still need work:\n#{names}"}
    end
  end

  def orchestrate(scope, session, opts \\ []) do
    ProjectCoordinator.default_orchestrate(__MODULE__, scope, session, opts)
  end

  def orchestrate_evaluate(scope, session, opts \\ []) do
    ProjectCoordinator.default_orchestrate_evaluate(__MODULE__, scope, session, opts)
  end

  defp all_requirements_satisfied?(component) do
    reqs = component.requirements || []

    Enum.all?(@implementation_reqs, fn req_name ->
      not Enum.any?(reqs, fn r -> r.name == req_name and not r.satisfied end)
    end)
  end
end
