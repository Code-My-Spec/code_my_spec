defmodule CodeMySpec.AgentTasks.Setup.IgnoredPaths do
  @moduledoc """
  Setup step: configure `.code_my_spec/config.yml` with `ignored_paths`.

  Framework and infrastructure modules generated by Phoenix (repo, mailer, endpoint,
  telemetry, router, gettext, error handlers, etc.) should be excluded from task graphs
  so they don't pollute requirements with generated boilerplate.
  """

  alias CodeMySpec.AgentTasks.Setup.{Context, Helpers}
  alias CodeMySpec.Paths

  @config_file Path.join(Paths.base_dir(), "config.yml")

  # Standard Phoenix-generated modules that should always be ignored.
  # These are the baseline — the agent prompt tells them to add more as needed.
  @standard_ignored_prefixes [
    "lib/APP/repo.ex",
    "lib/APP/mailer.ex",
    "lib/APP/application.ex",
    "lib/APP/release.ex",
    "lib/APP.ex",
    "lib/APP_web.ex",
    "lib/APP_web/application.ex",
    "lib/APP_web/endpoint.ex",
    "lib/APP_web/router.ex",
    "lib/APP_web/telemetry.ex",
    "lib/APP_web/gettext.ex",
    "lib/APP_web/components/core_components.ex",
    "lib/APP_web/components/layouts.ex",
    "lib/APP_web/controllers/error_*",
    "lib/APP_web/controllers/page_*"
  ]

  def check(%Context{} = ctx) do
    missing = "`.code_my_spec/config.yml` not found. Framework modules will pollute task graphs."

    case Context.error(ctx, @config_file, :ignored_paths, missing) do
      nil -> :valid
      msg -> {:invalid, msg}
    end
  end

  def evaluate(scope, _task) do
    scope |> Context.load() |> check() |> wrap()
  end

  defp wrap(:valid), do: {:ok, :valid}
  defp wrap({:invalid, reason}), do: {:ok, :invalid, reason}

  def command(scope, _task) do
    app_name = Helpers.extract_app_name(scope.environment) || "APP"

    example_paths =
      @standard_ignored_prefixes
      |> Enum.map(&String.replace(&1, "APP", app_name))
      |> Enum.map_join("\n", &"  - #{&1}")

    {:ok,
     """
     # Configure Ignored Paths

     Create `.code_my_spec/config.yml` with an `ignored_paths` list to exclude framework
     and infrastructure modules from task graphs. These are Phoenix-generated modules that
     should not be treated as project requirements.

     Start with these standard ignores and add any other generated/infrastructure modules
     (auth controllers from `phx.gen.auth`, health checks, PubSub, Vault, etc.):

     ```yaml
     ignored_paths:
     #{example_paths}
     ```

     Write this file to `#{@config_file}`. Review the project's `lib/` directory and add
     any additional framework or infrastructure modules that were generated, not authored.
     """}
  end
end
