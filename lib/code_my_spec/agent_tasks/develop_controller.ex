defmodule CodeMySpec.AgentTasks.DevelopController do
  @moduledoc """
  Container task for developing a Phoenix controller through its requirement lifecycle.

  Used by the `/develop-controller` skill and as a task module for `:orchestrate`
  scope requirements. The heavy orchestration is handled by `ProjectCoordinator`
  via `default_orchestrate/4`.

  Also ensures the companion JSON view has a stub spec so sync discovers it.

  `command/3` returns static development instructions (after ensuring JSON stub).
  `evaluate/3` checks whether the controller has all implementation requirements
  satisfied.
  """

  alias CodeMySpec.Components
  alias CodeMySpec.Components.ComponentRepository
  alias CodeMySpec.ProjectCoordinator
  alias CodeMySpec.Utils.Paths

  @implementation_reqs [
    "spec_file",
    "spec_valid",
    "implementation_file",
    "test_file",
    "tests_passing"
  ]

  def command(scope, task) do
    controller = Components.get_component!(scope, task.component_id)

    ensure_json_stub_spec(scope, controller)

    {:ok, """
    # Develop Controller: #{controller.name}

    Develop this controller through its requirement lifecycle.
    Invoke subagents for each prompt file generated by the orchestrator.

    ## Lifecycle Phases

    1. **Controller Spec** - Define controller actions, routes, and JSON view structure
    2. **Implementation** - Tests + code for both the controller and its JSON view

    **Note:** The implementation phase covers both the controller file and its
    companion JSON view file. Implement both in a single pass.

    ## Subagent Usage

    - For spec prompts: `@"CodeMySpec:spec-writer (agent)"`
    - For test prompts: `@"CodeMySpec:test-writer (agent)"`
    - For code prompts: `@"CodeMySpec:code-writer (agent)"`

    ## Completion

    When all tasks are complete, **stop the session** so the hook can validate.
    """}
  end

  def evaluate(scope, task) do
    controller = Components.get_component!(scope, task.component_id)
    controller = ComponentRepository.get_component(scope, controller.id)

    if all_requirements_satisfied?(controller) do
      {:ok, :valid}
    else
      reqs = controller.requirements || []

      unsatisfied =
        reqs
        |> Enum.filter(fn r -> r.name in @implementation_reqs and not r.satisfied end)
        |> Enum.map_join(", ", & &1.name)

      {:ok, :invalid, "Controller #{controller.module_name} still needs: #{unsatisfied}"}
    end
  end

  def orchestrate(scope, session, opts \\ []) do
    %{component: controller} = session
    ensure_json_stub_spec(scope, controller)
    ProjectCoordinator.default_orchestrate(__MODULE__, scope, session, opts)
  end

  def orchestrate_evaluate(scope, session, opts \\ []) do
    ProjectCoordinator.default_orchestrate_evaluate(__MODULE__, scope, session, opts)
  end

  # ============================================================================
  # JSON Stub Spec
  # ============================================================================

  defp ensure_json_stub_spec(scope, controller) do
    module_name = controller.module_name

    case json_module_name(module_name) do
      nil ->
        :ok

      json_module ->
        json_module_path = Paths.module_to_path(json_module)
        spec_path = CodeMySpec.Paths.spec_file(json_module_path)

        case CodeMySpec.Environments.file_exists?(scope.environment, spec_path) do
          true ->
            :ok

          _ ->
            content = """
            # #{json_module}

            JSON view companion for #{module_name}.

            ## Type

            json
            """

            CodeMySpec.Environments.write_file(scope.environment, spec_path, content)
        end
    end
  end

  defp json_module_name(controller_module_name) do
    if String.ends_with?(controller_module_name, "Controller") do
      String.replace_suffix(controller_module_name, "Controller", "JSON")
    else
      nil
    end
  end

  defp all_requirements_satisfied?(component) do
    reqs = component.requirements || []

    Enum.all?(@implementation_reqs, fn req_name ->
      not Enum.any?(reqs, fn r -> r.name == req_name and not r.satisfied end)
    end)
  end
end
