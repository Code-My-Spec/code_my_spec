defmodule CodeMySpec.AgentTasks.DevelopLiveView do
  @moduledoc """
  Container task for developing a LiveView through its requirement lifecycle.

  Used by the `/develop-liveview` skill and as a task module for `:orchestrate`
  scope requirements. The heavy orchestration is handled by `ProjectCoordinator`
  via `default_orchestrate/4`.

  `command/3` returns static development instructions.
  `evaluate/3` checks whether the LiveView and all child components have their
  implementation requirements satisfied.
  """

  alias CodeMySpec.Components
  alias CodeMySpec.Components.ComponentRepository
  alias CodeMySpec.Requirements

  @implementation_reqs [
    "spec_file",
    "spec_valid",
    "implementation_file",
    "test_file",
    "tests_passing"
  ]

  def command(scope, task) do
    liveview = Components.get_component!(scope, task.component_id)

    {:ok, """
    # Develop LiveView: #{liveview.name}

    Develop this LiveView through its requirement lifecycle.
    Invoke subagents for each prompt file generated by the orchestrator.

    ## Lifecycle Phases

    1. **LiveView Spec** - Define the LiveView architecture, route, interactions
    2. **Component Specs** - Design each child component
    3. **Implementation** - Tests + code in dependency order (children first, parent last)

    ## Subagent Usage

    - For spec prompts: `@"CodeMySpec:spec-writer (agent)"`
    - For test prompts: `@"CodeMySpec:test-writer (agent)"`
    - For code prompts: `@"CodeMySpec:code-writer (agent)"`

    ## Completion

    When all tasks are complete, **stop the session** so the hook can validate.
    """}
  end

  def evaluate(scope, task) do
    liveview = Components.get_component!(scope, task.component_id)
    liveview = ComponentRepository.get_component(scope, liveview.id)
    children = Components.list_child_components(scope, liveview.id)
    all = [liveview | children]

    missing = Enum.reject(all, &all_requirements_satisfied?(scope, &1))

    if Enum.empty?(missing) do
      {:ok, :valid}
    else
      names = Enum.map_join(missing, "\n", fn c -> "- #{c.module_name}" end)
      {:ok, :invalid, "Components still need work:\n#{names}"}
    end
  end

  def dispatch(_node) do
    "Implement a LiveView (or LiveComponent) — mount, handle_params, handle_event, " <>
      "render — against the spec's route, params, child components, interactions, " <>
      "and design. Use when the LiveView spec is valid and either its implementation " <>
      "file is missing or the existing implementation is failing its tests."
  end

  defp all_requirements_satisfied?(scope, component) do
    reqs = Requirements.compute_component_requirements(scope, component)

    Enum.all?(@implementation_reqs, fn req_name ->
      not Enum.any?(reqs, fn r -> r.name == req_name and not r.satisfied end)
    end)
  end
end
