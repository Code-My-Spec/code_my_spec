defmodule CodeMySpec.Provisioning.BurstBox.FlyPeering do
  @moduledoc """
  A temporary WireGuard peer from a Hetzner burst box into Fly's 6PN private
  network (story 877, build order item 4 — last, and deliberately isolated
  from everything else this task built).

  ## Why this exists, and why it is not permanent

  CodeMySpec's own app still runs on Fly today; moving it onto our own
  Hetzner infrastructure is a separate, already-backlogged piece of work. Until
  that migration lands, a Hetzner-hosted burst box's FLAME runners still need
  to dial back to a Fly-hosted parent (`FLAME.Terminator` dials out —
  `Node.connect(node(parent.pid))`, `deps/flame/lib/flame/terminator.ex`) over
  *some* network path, and Hetzner's own private networking
  (`CodeMySpec.Provisioning.Hetzner.ensure_network/3`) only reaches other
  Hetzner boxes in the same project — it has no route to Fly's 6PN at all.

  A WireGuard peer into Fly's 6PN is the accepted way to close that gap for
  now, and *only* for now — accepted as a temporary special case, not as the
  real cross-provider networking story. Everything that peer needs lives in
  this one file, called from nowhere `BurstBox.Lifecycle` or `BurstBox.Sweep`
  touch, specifically so the day that migration lands, deleting this module
  and its one caller is the whole removal. `lib/code_my_spec_web/application.ex`
  picking `FLAME.FlyBackend` for `EmbedPool` in prod (v2.0.291, inert without a
  configured `FLY_API_TOKEN`) is the other half of this same temporary state
  and is meant to go the same day — this module does not touch that file and
  is not what removes it.

  ## What this does not do

  This never talks to Fly's API. Nothing in this codebase has a Fly client
  today, and minting a peer (`flyctl wireguard create`, or Fly's GraphQL API
  directly) needs a Fly credential this task was not handed and has not
  verified against anything real. A peer's own parameters — this box's
  assigned 6PN address, Fly's gateway endpoint, Fly's own public key — arrive
  as plain data (`t:peer/0`), the same way `ssh_key_ids` arrives at
  `CodeMySpec.Provisioning.Hetzner.create_server/3` already minted rather
  than generated by it. Obtaining them today is a human running `flyctl
  wireguard create` once per environment; nothing here automates that step,
  and nothing here has been run against a real box or a real Fly 6PN either
  — see the field report for exactly what is and is not proven.

  ## Testable without a box

  `config/1` is pure string-building, the same way
  `CodeMySpec.Embeddings.HetznerFlameBackend.cloud_init/1` is. `apply/2` and
  `remove/1` are command sequences run through an injected `run` closure —
  `(list() -> {String.t(), non_neg_integer()})`, the exact shape
  `CodeMySpec.Provisioning.Builder.Remote.ssh_runner/2` already produces — so
  what a real box would be told to do is asserted here without ever reaching
  one. The config is written over the wire as base64 specifically so no
  quoting question (a key containing `/` or `+`, a config containing a
  newline) ever has to be answered inside a shell one-liner.
  """

  @type peer :: %{
          private_key: String.t(),
          address: String.t(),
          peer_public_key: String.t(),
          endpoint: String.t(),
          allowed_ips: String.t()
        }

  # One fixed name rather than caller-chosen: `remove/1` has to find what
  # `apply/2` made with no state of its own to look it up by, and a burst
  # box has exactly one reason to ever run this module at all.
  @interface "wg-cms-fly0"

  @doc "The interface name this module always uses."
  @spec interface() :: String.t()
  def interface, do: @interface

  @doc """
  The `wg-quick` config file for one peer.

  `peer.address` carries its own prefix (e.g. `"fdaa:1:2::3/120"`), matching
  how Fly itself hands these out — nothing here invents or validates a
  prefix on the caller's behalf, the same reason `Hetzner.create_server/3`
  does not validate the SSH key material it is handed.
  """
  @spec config(peer()) :: String.t()
  def config(%{
        private_key: private_key,
        address: address,
        peer_public_key: peer_public_key,
        endpoint: endpoint,
        allowed_ips: allowed_ips
      }) do
    """
    [Interface]
    PrivateKey = #{private_key}
    Address = #{address}

    [Peer]
    PublicKey = #{peer_public_key}
    Endpoint = #{endpoint}
    AllowedIPs = #{allowed_ips}
    PersistentKeepalive = 25
    """
  end

  @doc """
  Install `wireguard-tools` if it is not already there, write `peer`'s
  config, and bring the interface up.

  Idempotent: re-applying the same (or a changed) peer onto a box that
  already has this interface brings it down first — `wg-quick down` on an
  absent interface simply fails, which is why that step is never checked —
  then writes the new file and brings it back up, rather than refusing on
  `wg-quick up`'s own "already exists" error.
  """
  @spec apply(peer(), (list() -> {String.t(), non_neg_integer()})) :: :ok | {:error, term()}
  def apply(peer, run) when is_function(run, 1) do
    path = config_path()

    with {_, 0} <- run.([ensure_installed_command()]),
         {_, 0} <- run.(["mkdir -p /etc/wireguard"]),
         {_, 0} <- run.([write_config_command(peer, path)]),
         {_, 0} <- run.(["chmod 600 #{path}"]),
         {_, 0} <- run.([up_command()]) do
      :ok
    else
      {output, status} -> {:error, {status, String.trim(to_string(output))}}
    end
  end

  @doc """
  Bring the interface down and remove its config — the whole teardown, for
  the same reason `CodeMySpec.Provisioning.Builder` destroys the box it made
  on every path: nothing here must survive this module no longer being
  called.

  Idempotent the same way `apply/2` is: `wg-quick down` failing on an
  already-absent interface does not fail this call, because the chained
  `rm -f` after it is what this function's own success is judged on.
  """
  @spec remove((list() -> {String.t(), non_neg_integer()})) :: :ok | {:error, term()}
  def remove(run) when is_function(run, 1) do
    case run.(["wg-quick down #{@interface} >/dev/null 2>&1 ; rm -f #{config_path()}"]) do
      {_, 0} -> :ok
      {output, status} -> {:error, {status, String.trim(to_string(output))}}
    end
  end

  defp config_path, do: "/etc/wireguard/#{@interface}.conf"

  defp ensure_installed_command do
    "command -v wg-quick >/dev/null 2>&1 || " <>
      "(apt-get update -qq && DEBIAN_FRONTEND=noninteractive apt-get install -y -qq wireguard-tools)"
  end

  # Base64 over the wire, decoded on the box, rather than a heredoc or an
  # escaped literal: a WireGuard key is already base64 (so it can itself
  # contain `/` and `+`), and the config this wraps a key inside of is
  # multi-line — both are exactly the content a shell one-liner's own
  # quoting rules are least equipped to carry safely.
  defp write_config_command(peer, path) do
    encoded = peer |> config() |> Base.encode64()
    "echo #{encoded} | base64 -d > #{path}"
  end

  defp up_command, do: "wg-quick down #{@interface} >/dev/null 2>&1 ; wg-quick up #{@interface}"
end
