defmodule CodeMySpec.McpServers.Devops.Tools.ImportAgeKey do
  @moduledoc """
  Record an environment's age key when it was generated on a real checkout
  this server cannot reach, rather than minted here.

  `.sops.yaml` and an environment's `envs/*.enc.env` are files that live in
  and get committed to a project's own working tree — real local-filesystem
  work, the same category as `:repository`'s git push, and just as
  unreachable through the light harness for a project with no checkout on
  this side. When that local work happens somewhere that *does* have a real
  checkout instead (a developer's own machine, a harness with a live
  registration), the private half of the key it generated still has to land
  here — or the next thing on this side that needs to decrypt (`:deploy`,
  another secret write) mints a *different* key under the same name, and
  every ciphertext already committed under the real one becomes unreadable
  to it.
  """

  use Anubis.Server.Component, type: :tool

  alias Anubis.Server.Response
  alias CodeMySpec.McpServers.Validators
  alias CodeMySpec.Projects
  alias CodeMySpec.Provisioning.Steps
  alias CodeMySpec.Resources

  schema do
    field :project_id, :string, required: true, doc: "Import the key for this project."

    field :environment, :string,
      required: true,
      doc: "Environment name, e.g. \"prod\" or \"uat\"."

    field :private_key, :string,
      required: true,
      doc: "The environment's private age key (AGE-SECRET-KEY-...), as generated by age-keygen."
  end

  @impl true
  def execute(
        %{project_id: project_id, environment: environment, private_key: private_key} = params,
        frame
      ) do
    with {:ok, scope} <- Validators.validate_local_scope(frame, params),
         {:ok, project} <- find_project(scope, project_id) do
      scope
      |> Resources.project_scope(project)
      |> Steps.import_age_key(environment, private_key)
      |> reply(environment, frame)
    else
      {:error, reason} -> {:reply, error(reason), frame}
    end
  end

  defp find_project(scope, project_id) do
    case Enum.find(Projects.list_projects(scope), &(&1.id == project_id)) do
      nil -> {:error, "no project #{project_id} on this account"}
      project -> {:ok, project}
    end
  end

  defp reply({:ok, public}, environment, frame),
    do:
      {:reply,
       ok(
         "#{environment}'s key is on file. Its public half is #{public} — " <>
           "confirm this matches the recipient already committed in .sops.yaml."
       ), frame}

  defp reply({:error, reason}, _environment, frame), do: {:reply, error(reason), frame}

  defp ok(text), do: Response.tool() |> Response.text(text)

  defp error(reason),
    do: Response.tool() |> Response.error("Could not import the key: #{inspect(reason)}")
end
