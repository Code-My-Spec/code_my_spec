defmodule CodeMySpec.McpServers.Hexdocs.Tools.SearchHexdocs do
  @moduledoc """
  Semantic search across embedded hex dependency documentation.

  Searches embeddings generated by embed_hexdocs. Returns the most relevant
  documentation chunks for the query.
  """

  use Anubis.Server.Component, type: :tool

  alias CodeMySpec.Embeddings
  alias CodeMySpec.McpServers.Validators

  schema do
    field :query, :string, required: true, description: "Natural language search query"

    field :package, :string,
      description: "Filter to a specific package (e.g. 'phoenix'). Omit to search all."

    field :limit, :integer, description: "Max results (default: 10)"
  end

  @impl true
  def execute(%{query: query} = params, frame) do
    with {:ok, scope} <- Validators.validate_local_scope(frame) do
      source =
        case params[:package] do
          pkg when is_binary(pkg) and pkg != "" -> "hexdocs:#{pkg}"
          _ -> nil
        end

      opts =
        [limit: params[:limit] || 10]
        |> then(fn opts -> if source, do: Keyword.put(opts, :source, source), else: opts end)

      case Embeddings.search(scope, query, opts) do
        {:ok, results} ->
          {:reply, text_response(format_results(query, results)), frame}

        {:error, :embeddings_unavailable} ->
          {:reply,
           error_response(
             "Embeddings are unavailable in this runtime. The embed pipeline (Ortex + sqlite_vec) ships only with the CodeMySpec CLI binary."
           ), frame}

        {:error, reason} ->
          {:reply, error_response("#{inspect(reason)}"), frame}
      end
    else
      {:error, reason} ->
        {:reply, error_response("#{reason}"), frame}
    end
  end

  defp format_results(query, results) do
    header = "# Hex Docs Search: \"#{query}\"\n\n**#{length(results)} results**\n"

    body =
      if results == [] do
        "\nNo matches found. Run `embed_hexdocs` first to generate embeddings."
      else
        Enum.map_join(results, "\n\n---\n\n", fn result ->
          # source is "hexdocs:package_name"
          package = String.replace_prefix(result.source, "hexdocs:", "")

          """
          **#{package}** — #{result.path} (chunk #{result.chunk_index})

          #{String.slice(result.content, 0, 500)}#{if String.length(result.content) > 500, do: "...", else: ""}
          """
        end)
      end

    header <> "\n" <> body
  end

  defp text_response(content) do
    Anubis.Server.Response.tool()
    |> Anubis.Server.Response.text(content)
  end

  defp error_response(message) do
    Anubis.Server.Response.tool()
    |> Anubis.Server.Response.error(message)
  end
end
