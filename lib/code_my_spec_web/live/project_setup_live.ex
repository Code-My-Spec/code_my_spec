defmodule CodeMySpecWeb.ProjectSetupLive do
  @moduledoc """
  Brownfield onboarding: what an existing Phoenix project still needs before it
  can be worked on here.

  ## Why this is its own page

  It used to be a requirement. `project_setup` was a node in `project_graph`,
  and this page was `RequirementsLive` rendering that node by name — so setup
  arrived through `get_next_requirement` as ordinary work, alongside "write the
  spec for this context".

  That stopped being true when `cms new` started covering setup. **The mainline
  exits `cms new` with setup complete — that is the promise.** A project
  generated by us has nothing here to do, and offering it the checklist is
  offering work that does not exist.

  What survives is the case `cms new` cannot serve: an Elixir project that
  already exists and is being brought in. That is not a phase of the workflow,
  it is a door into it, so it is reached explicitly rather than handed out by
  the graph.

  ## What it renders

  `AgentTasks.ProjectSetup.command/2` — the same checklist as before, because
  the checklist was never the problem. It reports `N/12` and inlines the full
  prompt of every step that is not yet satisfied, so the page is both the status
  and the instructions.

  No requirement graph is involved. That is the point: this reads the working
  copy directly, which is exactly why it could never be cached alongside
  requirements that read rows.
  """

  use CodeMySpecWeb, :live_view

  import CodeMySpecWeb.Markdown, only: [md_html: 1]

  alias CodeMySpec.AgentTasks.ProjectSetup
  alias CodeMySpec.Projects

  @impl true
  def mount(%{"project_id" => project_id}, _session, socket) do
    scope = socket.assigns.current_scope

    case Projects.get_project_by_id(project_id) do
      nil ->
        {:ok,
         socket
         |> put_flash(:error, "No such project")
         |> push_navigate(to: ~p"/app/projects")}

      project ->
        scope = %{scope | active_project: project, active_project_id: project.id}
        {:ok, assign_checklist(socket, scope, project)}
    end
  end

  defp assign_checklist(socket, scope, project) do
    # A failure here is shown rather than raised: the steps shell out and read
    # the working copy, and "the checklist could not be built" is a different
    # thing from "setup is incomplete". Conflating them would tell someone their
    # project needs work when what actually happened is that we could not look.
    {checklist, error} =
      case ProjectSetup.command(scope, %{}) do
        {:ok, text} -> {text, nil}
        {:error, reason} -> {nil, inspect(reason)}
      end

    socket
    # `:setup` rather than `:requirements` — the layout renders it as the
    # breadcrumb and the nav highlight, and this is no longer a requirement.
    # `section_path/1` derives the crumb from the atom, so no layout change is
    # needed to add one.
    |> assign(:section, :setup)
    |> assign(:page_title, "Project Setup")
    |> assign(:project, project)
    |> assign(:checklist, checklist)
    |> assign(:setup_error, error)
  end

  @impl true
  def render(assigns) do
    ~H"""
    <div class="max-w-4xl mx-auto p-4">
      <.link navigate={~p"/app/projects"} class="text-sm text-base-content/60 hover:underline">
        ← Projects
      </.link>

      <h1 class="text-2xl font-bold mt-2 mb-1">Project Setup</h1>

      <p class="text-sm text-base-content/60 mb-4">
        Onboarding for an existing Phoenix project. A project generated by
        <code class="font-mono">cms new</code>
        exits with setup already complete and has nothing to do here.
      </p>
      
    <!-- `data-role` rather than a class: the spex select on it, and a class is a
           styling decision that should be free to change without breaking a test. -->
      <div :if={@setup_error} data-role="setup-error" class="alert alert-error mb-4" role="alert">
        <span>Could not read this project's setup state: {@setup_error}</span>
      </div>

      <div
        :if={@checklist}
        class="prose prose-sm md:prose-base max-w-none bg-base-200 border border-base-300 rounded-box p-6 overflow-x-auto"
      >
        {md_html(@checklist)}
      </div>
    </div>
    """
  end
end
