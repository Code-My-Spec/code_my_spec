defmodule CodeMySpecWeb.CmsUsersController do
  @moduledoc """
  Lists this application's registered users for the CodeMySpec dashboard.

  Authenticated by the deployment key (`Authorization: Bearer <DEPLOY_KEY>`
  matching `:code_my_spec, :deploy_key`) — the same credential content sync
  uses; the caller is the CodeMySpec server, not an end user. Read-only:
  returns each user's email and registration date, paginated.

  Repo access lives in `CodeMySpec.CmsUsers` (domain boundary); this
  controller only authenticates and renders. Generated by
  `mix client_utils.gen.cms_users` — safe to edit, but a re-run overwrites it.
  """

  use CodeMySpecWeb, :controller

  alias CodeMySpec.CmsUsers

  @default_page_size 50
  @max_page_size 100

  def index(conn, params) do
    case validate_deploy_key(conn) do
      :ok ->
        page = parse_page(params["page"])
        page_size = parse_page_size(params["page_size"])
        users = CmsUsers.list_registered_users(page, page_size)
        total = CmsUsers.count_registered_users()

        json(conn, %{
          data: Enum.map(users, &%{email: &1.email, registered_at: &1.inserted_at}),
          page: page,
          page_size: page_size,
          total: total
        })

      # An aged-out token, not a wrong one. `reason` is what tells the app to
      # renew and retry rather than go looking at its configuration —
      # criterion 8023 is precisely this distinction.
      {:error, :expired} ->
        conn
        |> put_status(:unauthorized)
        |> json(%{error: "Access token expired", reason: "expired"})

      {:error, :unauthorized} ->
        conn |> put_status(:unauthorized) |> json(%{error: "Invalid deployment key"})

      {:error, :missing_deploy_key} ->
        conn |> put_status(:unauthorized) |> json(%{error: "Missing deployment key"})

      {:error, :deploy_key_not_configured} ->
        conn |> put_status(:internal_server_error) |> json(%{error: "Deploy key not configured"})
    end
  end

  defp parse_page(value) when is_binary(value) do
    case Integer.parse(value) do
      {n, _} when n > 0 -> n
      _ -> 1
    end
  end

  defp parse_page(_), do: 1

  defp parse_page_size(value) when is_binary(value) do
    case Integer.parse(value) do
      {n, _} when n > 0 -> min(n, @max_page_size)
      _ -> @default_page_size
    end
  end

  defp parse_page_size(_), do: @default_page_size

  # Auth — mirrors the content sync deploy-key check (constant-time compare).
  # See `ContentSyncController` — a token proves the caller exchanged a secret
  # we issued, and stands in for the configured key without widening this to
  # authorize any project that happens to hold a deploy key.
  defp validate_deploy_key(conn) do
    case CodeMySpecWeb.AppCredential.token(conn) do
      {:ok, _project} -> :ok
      {:error, :expired} -> {:error, :expired}
      {:error, _} -> validate_configured_deploy_key(conn)
    end
  end

  defp validate_configured_deploy_key(conn) do
    with {:ok, expected} <- expected_deploy_key(),
         {:ok, provided} <- bearer_token(conn) do
      if secure_compare(expected, provided), do: :ok, else: {:error, :unauthorized}
    end
  end

  defp expected_deploy_key do
    case Application.get_env(:code_my_spec, :deploy_key) do
      nil -> {:error, :deploy_key_not_configured}
      "" -> {:error, :deploy_key_not_configured}
      key -> {:ok, key}
    end
  end

  defp bearer_token(conn) do
    case get_req_header(conn, "authorization") do
      ["Bearer " <> token] -> {:ok, token}
      _ -> {:error, :missing_deploy_key}
    end
  end

  defp secure_compare(left, right) do
    if byte_size(left) == byte_size(right) do
      Plug.Crypto.secure_compare(left, right)
    else
      Plug.Crypto.secure_compare(left, left)
      false
    end
  end
end
