defmodule CodeMySpec.Repo.Migrations.CreateFileAnalyses do
  use Ecto.Migration

  @moduledoc """
  The SQLite counterpart of the Postgres `create_file_analyses`, and identical
  to it: the id is generated by the application via `Ecto.UUID`, so there is no
  database default to differ on.

  What an analyzer actually looked at, and at what content.

  Two facts an analyzer produces, and until now only one was recorded:

      "this file had this problem at this content"  -> problems.file_fingerprint
      "this file was clean at this content"         -> nothing

  So a file with no problems has been indistinguishable from a file nobody
  analysed. `tests_passing` and `no_problems` are `count == 0` — they read
  "clean" out of an absence. That is the project's standing invariant sitting in
  the schema rather than in a message: absent information must not render as
  good news.

  This is the missing half. One row per `(file, source)` saying which content
  that analyzer saw, so "clean" and "unlooked-at" stop being the same answer.

  ## Why upsert rather than a row per run

  Only current coverage is a fact anyone asks about. A row per file per run
  keeps history nobody queries and grows fast — an exunit run covers ~1,200
  files here, and at a run every couple of minutes that is hundreds of thousands
  of rows a day per working copy. `analysis_runs` already needed
  `RunsRepository.prune/2` at a thousandth of that volume.

  Upserting on `(harness_id, file_id, source)` holds ~5,800 rows per working
  copy, flat. Run history stays in `analysis_runs`, where it is already pruned,
  and `run_id` here keeps the provenance link.

  ## Why the fingerprint is a column and not a join

  The fingerprint recorded must be **the one the analyzer saw**, not the one the
  file has now. Reading it from `files` at reconcile time would record "analysed
  at the current content" for a file whose older bytes the tool actually read —
  a false fact, written down permanently, which is worse than a stale message
  because nothing later contradicts it. So the value travels with the result and
  is stored, not derived.

  ## Keyed on the harness

  Same grain as `files`, `problems` and `analysis_runs`. Two checkouts of one
  project analyse different trees; coverage is per working copy or it is
  meaningless.
  """

  def change do
    create table(:file_analyses, primary_key: false) do
      add :id, :binary_id, primary_key: true

      add :file_id, references(:files, type: :binary_id, on_delete: :delete_all), null: false

      add :project_id, references(:projects, type: :binary_id, on_delete: :delete_all),
        null: false

      add :harness_id, references(:harnesses, type: :binary_id, on_delete: :delete_all),
        null: false

      # compiler | credo | exunit | spex. A string rather than an enum for the
      # same reason `analysis_runs.source` is one: sources are added by
      # configuration more often than by migration.
      add :source, :string, null: false

      # The content the analyzer read. Not nullable — a coverage row whose
      # fingerprint is unknown asserts nothing and would reintroduce exactly the
      # ambiguity this table exists to remove.
      add :fingerprint, :string, null: false

      # When the analyzer read it, which is not when the row was written.
      add :analyzed_at, :utc_datetime_usec, null: false

      # Provenance. Nilified rather than cascading: pruning old runs must not
      # delete current coverage, or the pruner silently un-analyses the project.
      add :run_id, references(:analysis_runs, on_delete: :nilify_all)

      timestamps(type: :utc_datetime)
    end

    # The upsert target.
    create unique_index(:file_analyses, [:harness_id, :file_id, :source])

    # "Which files does this source still cover, and are they current" — the
    # freshness query, per working copy.
    create index(:file_analyses, [:harness_id, :source])

    # "Has anything analysed this file" — the per-file question the requirement
    # graph needs before it can read `count == 0` as clean.
    create index(:file_analyses, [:file_id])
  end
end
