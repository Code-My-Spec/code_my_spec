defmodule CodeMySpec.CodeGenerationFixtures do
  @moduledoc """
  Seeds an `InMemoryEnvironment` for BDD specs covering the
  `CodeMySpec.AgentTasks.CodeGeneration` task. Used by Story
  "Standard stack code generation".

  ## Design

  The CodeGeneration task is a prompt builder + thin evaluator. It
  reads four sources from disk and returns a markdown prompt:

  | Source                              | What it drives in the prompt              |
  |-------------------------------------|-------------------------------------------|
  | `mix.exs`                           | App name resolution for detection paths   |
  | `.code_my_spec/architecture/decisions/*.md` | Technical Decisions section       |
  | `.code_my_spec/integrations/*.md`   | Integration Providers section             |
  | `.code_my_spec/tasks/code_generation.sh` | Existing Generation Script section   |
  | Standard generator detection files  | Current Status checkbox list              |

  Each public function here writes ONE of those sources. Scenarios
  compose them. The fixtures are intentionally richer than a bare
  detection file — every helper writes content that mirrors what a
  real Phoenix project would produce, so that prompts assembled in
  specs read like prompts the agent sees in production.

  ## Generators

  `@generators` is the ordered list of standard CodeMySpec
  generators. Each entry mirrors the corresponding row in
  `CodeMySpec.AgentTasks.CodeGeneration.@generators` — id, command,
  detection path (with `APP`/`APP_web` placeholders), and a stub
  body that's installed at the detection path when that generator
  is marked as already-applied.

  Stubs are deliberately small (one module body, no migrations or
  test files). The CodeGeneration task's detection only checks
  `file_exists?` on a single path per generator, so larger stubs
  add cost without coverage. If detection grows to scan additional
  paths, expand the stubs here.

  ## App identity

  `app_name/0` and `app_mod/0` lock the project's identity at
  `:my_app` / `MyApp` — same as `SetupFixtures`. Detection paths
  are resolved against `app_name/0`. Tests that need a different
  app name should reset and call `with_baseline_project/2`
  directly.

  ## Composition with SetupFixtures

  `with_baseline_project/1` is a higher-fidelity replacement for
  `SetupFixtures.satisfy(env, [])`. The mix.exs we write declares
  the standard CodeMySpec stack so the "Current Dependencies"
  experience matches a post-`technical_strategy` project. Specs
  that need step-by-step setup state should still reach for
  `SetupFixtures` — this module is for code-generation-specific
  state.

  ## Reset

  Delegates to `SetupFixtures.reset/1` (in-memory env wipe).
  Scenarios within a spex block share the env; reset at the start
  of each scenario that needs a clean slate.
  """

  alias CodeMySpec.Environments
  alias CodeMySpec.Environments.Environment
  alias CodeMySpec.SetupFixtures

  @app_name "my_app"
  @app_mod "MyApp"

  @decisions_dir ".code_my_spec/architecture/decisions"
  @integrations_dir ".code_my_spec/integrations"
  @script_path ".code_my_spec/tasks/code_generation.sh"

  # Each generator: {id, command, detection_path_with_APP_placeholder, stub_body_template}
  @generators [
    {
      "phx_gen_auth",
      "mix phx.gen.auth Users User users --live",
      "lib/APP/users/scope.ex",
      """
      defmodule APP_MOD.Users.Scope do
        @moduledoc \"\"\"
        Scope generated by `mix phx.gen.auth`. Carries the current user
        and any session-scoped identifiers through the request lifecycle.
        \"\"\"

        alias APP_MOD.Users.User

        defstruct user: nil, user_token: nil

        @type t :: %__MODULE__{user: User.t() | nil, user_token: binary() | nil}

        def for_user(%User{} = user), do: %__MODULE__{user: user}
        def for_user(nil), do: nil
      end
      """
    },
    {
      "cms_gen_accounts",
      "mix cms_gen.accounts",
      "lib/APP/accounts/account.ex",
      """
      defmodule APP_MOD.Accounts.Account do
        @moduledoc \"\"\"
        Account schema generated by `mix cms_gen.accounts`. Owns the
        multi-tenant boundary — every domain row belongs to exactly
        one Account.
        \"\"\"

        use Ecto.Schema
        import Ecto.Changeset

        schema "accounts" do
          field :name, :string
          field :slug, :string
          timestamps()
        end

        def changeset(account, attrs) do
          account
          |> cast(attrs, [:name, :slug])
          |> validate_required([:name, :slug])
          |> unique_constraint(:slug)
        end
      end
      """
    },
    {
      "cms_gen_integrations",
      "mix cms_gen.integrations",
      "lib/APP/integrations/integration.ex",
      """
      defmodule APP_MOD.Integrations.Integration do
        @moduledoc \"\"\"
        Integration schema generated by `mix cms_gen.integrations`.
        Stores per-account OAuth credentials with encrypted tokens.
        \"\"\"

        use Ecto.Schema
        import Ecto.Changeset

        schema "integrations" do
          field :provider, :string
          field :access_token, APP_MOD.Encrypted.Binary
          field :refresh_token, APP_MOD.Encrypted.Binary
          field :expires_at, :utc_datetime
          belongs_to :account, APP_MOD.Accounts.Account
          timestamps()
        end

        def changeset(integration, attrs) do
          integration
          |> cast(attrs, [:provider, :access_token, :refresh_token, :expires_at, :account_id])
          |> validate_required([:provider, :account_id])
        end
      end
      """
    },
    {
      "cms_gen_feedback_widget",
      "mix cms_gen.feedback_widget",
      "lib/APP_web/live/feedback_widget.ex",
      """
      defmodule APP_MOD_WEB.FeedbackWidget do
        @moduledoc \"\"\"
        Feedback widget generated by `mix cms_gen.feedback_widget`.
        Captures screenshots and free-text feedback from end users
        via a LiveComponent embedded in the host application.
        \"\"\"

        use APP_MOD_WEB, :live_component

        def render(assigns) do
          ~H\"\"\"
          <div id="feedback-widget" phx-hook="FeedbackWidget">
            <button phx-click="open" phx-target={@myself}>Send feedback</button>
          </div>
          \"\"\"
        end
      end
      """
    }
  ]

  # ──────────────────────────────────────────────────────────────────────────
  # App identity
  # ──────────────────────────────────────────────────────────────────────────

  @doc "App name baked into the baseline mix.exs (`:my_app`)."
  @spec app_name() :: String.t()
  def app_name, do: @app_name

  @doc "App module name baked into the baseline mix.exs (`MyApp`)."
  @spec app_mod() :: String.t()
  def app_mod, do: @app_mod

  @doc "Path of the durable code generation artifact."
  @spec script_path() :: String.t()
  def script_path, do: @script_path

  @doc "Decisions directory path."
  @spec decisions_dir() :: String.t()
  def decisions_dir, do: @decisions_dir

  @doc "Integrations directory path."
  @spec integrations_dir() :: String.t()
  def integrations_dir, do: @integrations_dir

  @doc "Ordered list of generator IDs the standard stack runs."
  @spec generator_ids() :: [String.t()]
  def generator_ids, do: Enum.map(@generators, fn {id, _, _, _} -> id end)

  # ──────────────────────────────────────────────────────────────────────────
  # Baseline / reset
  # ──────────────────────────────────────────────────────────────────────────

  @doc """
  Write a baseline `mix.exs` that mirrors a post-`technical_strategy`
  project: app identity locked to `:my_app`, deps listing the
  standard CodeMySpec stack.

  Idempotent — only writes if `mix.exs` is absent.
  """
  @spec with_baseline_project(Environment.t()) :: :ok
  def with_baseline_project(env) do
    unless Environments.file_exists?(env, "mix.exs") do
      Environments.write_file(env, "mix.exs", """
      defmodule #{@app_mod}.MixProject do
        use Mix.Project

        def project do
          [
            app: :#{@app_name},
            version: "0.1.0",
            elixir: "~> 1.17",
            compilers: [:boundary, :spex] ++ Mix.compilers(),
            deps: deps()
          ]
        end

        def application do
          [mod: {#{@app_mod}.Application, []}, extra_applications: [:logger]]
        end

        defp deps do
          [
            {:phoenix, "~> 1.7"},
            {:phoenix_live_view, "~> 1.0"},
            {:ecto_sql, "~> 3.12"},
            {:postgrex, ">= 0.0.0"},
            {:swoosh, "~> 1.5"},
            {:dotenvy, "~> 1.0"},
            {:sexy_spex, "~> 0.1"},
            {:wallaby, "~> 0.30", only: :test},
            {:exvcr, "~> 0.15", only: :test},
            {:credo, "~> 1.7", only: [:dev, :test]}
          ]
        end
      end
      """)
    end

    :ok
  end

  @doc "Wipe every file from the in-memory env. Delegates to SetupFixtures."
  @spec reset(Environment.t()) :: :ok
  defdelegate reset(env), to: SetupFixtures

  # ──────────────────────────────────────────────────────────────────────────
  # Decision records (ADRs)
  # ──────────────────────────────────────────────────────────────────────────

  @doc """
  Write a decision record (ADR) for `topic` in the standard
  `.code_my_spec/architecture/decisions/<topic>.md` shape.

  Optionally accepts a `:title` and `:body` to customize the
  rendered ADR — useful for retrofit scenarios that assert on
  hand-written content.
  """
  @spec with_decision(Environment.t(), String.t(), keyword()) :: :ok
  def with_decision(env, topic, opts \\ []) do
    title = Keyword.get(opts, :title, "Use #{topic}")
    body = Keyword.get(opts, :body, "Use #{topic} as the standard choice.")

    Environments.write_file(env, "#{@decisions_dir}/#{topic}.md", """
    # #{title}

    ## Status
    Accepted

    ## Context
    Standard stack decision recorded by the technical_strategy phase.

    ## Decision
    #{body}

    ## Consequences
    Pre-made decision — see the index for the full set.
    """)
  end

  @doc "Write multiple decision records in one call."
  @spec with_decisions(Environment.t(), [String.t()]) :: :ok
  def with_decisions(env, topics) when is_list(topics) do
    Enum.each(topics, &with_decision(env, &1))
    :ok
  end

  # ──────────────────────────────────────────────────────────────────────────
  # Integration specs
  # ──────────────────────────────────────────────────────────────────────────

  @doc """
  Write an integration spec at
  `.code_my_spec/integrations/<provider>.md`. Specs are how the
  CodeGeneration task discovers which providers to scaffold via
  `cms_gen.integration_provider`.
  """
  @spec with_integration_spec(Environment.t(), String.t()) :: :ok
  def with_integration_spec(env, provider) do
    display_name =
      provider
      |> String.split(["_", "-"])
      |> Enum.map_join(" ", &String.capitalize/1)

    Environments.write_file(env, "#{@integrations_dir}/#{provider}.md", """
    # #{display_name} Integration

    ## Provider Key
    #{provider}

    ## Display Name
    #{display_name}

    ## Scopes
    - read:user
    - read:account

    ## Notes
    Integration spec written for the BDD spec fixture. Consumed by
    `mix cms_gen.integration_provider #{display_name} #{provider}`.
    """)
  end

  @doc "Write multiple integration specs in one call."
  @spec with_integration_specs(Environment.t(), [String.t()]) :: :ok
  def with_integration_specs(env, providers) when is_list(providers) do
    Enum.each(providers, &with_integration_spec(env, &1))
    :ok
  end

  # ──────────────────────────────────────────────────────────────────────────
  # Generator detection state
  # ──────────────────────────────────────────────────────────────────────────

  @doc """
  Mark a single generator as "already applied" by writing its
  detection file with a realistic stub body.

  Raises if `generator_id` isn't one of `generator_ids/0`.
  """
  @spec with_generator_applied(Environment.t(), String.t()) :: :ok
  def with_generator_applied(env, generator_id) do
    case Enum.find(@generators, fn {id, _, _, _} -> id == generator_id end) do
      {_id, _cmd, glob, stub} ->
        Environments.write_file(env, resolve_glob(glob), expand_stub(stub))
        :ok

      nil ->
        raise ArgumentError,
              "Unknown generator #{inspect(generator_id)}. Known: #{inspect(generator_ids())}"
    end
  end

  @doc """
  Mark every standard generator as applied. Use for the
  "all generators have run" scenario.
  """
  @spec with_all_generators_applied(Environment.t()) :: :ok
  def with_all_generators_applied(env) do
    Enum.each(@generators, fn {id, _, _, _} -> with_generator_applied(env, id) end)
    :ok
  end

  @doc """
  Returns true if a generator's detection file exists in `env`.
  Mirrors the heuristic the CodeGeneration task uses.
  """
  @spec generator_applied?(Environment.t(), String.t()) :: boolean()
  def generator_applied?(env, generator_id) do
    case Enum.find(@generators, fn {id, _, _, _} -> id == generator_id end) do
      {_id, _cmd, glob, _stub} ->
        Environments.file_exists?(env, resolve_glob(glob)) == true

      nil ->
        raise ArgumentError, "Unknown generator #{inspect(generator_id)}"
    end
  end

  # ──────────────────────────────────────────────────────────────────────────
  # Generation script
  # ──────────────────────────────────────────────────────────────────────────

  @doc """
  Write `code_generation.sh` recording every standard generator
  command. Use for "agent has finished" scenarios where a populated
  script is the gating artifact.
  """
  @spec with_full_script(Environment.t()) :: :ok
  def with_full_script(env) do
    body = """
    #!/bin/bash
    # Code generation script — produced by CodeMySpec code_generation task
    # Re-run on a fresh Phoenix project to reproduce this scaffold.

    set -e

    """

    commands =
      @generators
      |> Enum.map_join("\n\n", fn {_id, cmd, _glob, _stub} ->
        "# #{cmd}\n#{cmd}"
      end)

    Environments.write_file(env, @script_path, body <> commands <> "\n")
    :ok
  end

  @doc """
  Write a shebang-only "no generators needed" script. Models the
  minimal-project happy path where no generators were applicable
  and the agent recorded that explicitly.
  """
  @spec with_empty_script(Environment.t()) :: :ok
  def with_empty_script(env) do
    Environments.write_file(env, @script_path, """
    #!/bin/bash
    # No generators needed for this project.
    """)
  end

  @doc """
  Write a custom `code_generation.sh` body. Use for retrofit
  scenarios that assert on the prompt's "existing script" branch.
  """
  @spec with_existing_script(Environment.t(), String.t()) :: :ok
  def with_existing_script(env, body) when is_binary(body) do
    Environments.write_file(env, @script_path, body)
    :ok
  end

  @doc "Read `code_generation.sh`. Returns content or nil if missing."
  @spec read_script(Environment.t()) :: String.t() | nil
  def read_script(env) do
    case Environments.read_file(env, @script_path) do
      {:ok, content} -> content
      _ -> nil
    end
  end

  @doc "Returns true if `code_generation.sh` exists."
  @spec script_exists?(Environment.t()) :: boolean()
  def script_exists?(env) do
    Environments.file_exists?(env, @script_path) == true
  end

  # ──────────────────────────────────────────────────────────────────────────
  # Internals
  # ──────────────────────────────────────────────────────────────────────────

  defp resolve_glob(glob) do
    web_name = "#{@app_name}_web"

    glob
    |> String.replace("APP_web", web_name)
    |> String.replace("APP", @app_name)
  end

  defp expand_stub(stub) do
    web_mod = "#{@app_mod}Web"

    stub
    |> String.replace("APP_MOD_WEB", web_mod)
    |> String.replace("APP_MOD", @app_mod)
  end
end
