defmodule CodeMySpec.Problems.MissingPreconditionNoticeTest do
  @moduledoc """
  A criterion that never reached an assertion has not regressed, and the footer
  has to say which.

  `d145faae`. `docker/fleet/keys/fleet` is gitignored and generated by
  `docker/fleet/fleet.sh up` into whichever working copy ran it, so every
  criterion needing the fleet box is unpassable in every *other* checkout —
  while the fleet itself is running fine. `CodeMySpecSpex.Case.fleet_box/1`
  raises before any assertion executes, deliberately: a criterion that quietly
  passed without running the commands it is about would be the worse failure.

  What made it expensive is the same shape as the killed-process notice next
  door: the advice was confident and wrong. The footer said these "went green
  once and are red now, which is a regression in this working copy", and offered
  fix-or-park. Fixing is impossible from the wrong checkout, and parking means
  changing `ready_for_dev` on someone else's story to unblock your own session —
  the worst available move, and the one the wording nudged toward. The block is
  machine-wide: five worktrees held by a precondition living in one.
  """

  use ExUnit.Case, async: true

  alias CodeMySpec.Problems.{Problem, ProblemRenderer}

  @notice "never reached an assertion"

  defp blocked(file) do
    %Problem{
      source: "spex",
      severity: :error,
      file_path: file,
      line: 1,
      message:
        "Last night's dump is there in the morning — : No fleet key at " <>
          "/Users/dev/project/docker/fleet/keys/fleet.\n\nBring it up with:\n\n" <>
          "    docker/fleet/fleet.sh up"
    }
  end

  defp real(file) do
    %Problem{
      source: "spex",
      severity: :error,
      file_path: file,
      line: 40,
      message: "expected the deploy step to record an image"
    }
  end

  defp render(problems), do: ProblemRenderer.render_stop_response(problems, [])

  test "a precondition that cannot be met here says so, and says it is not a regression" do
    text = render([blocked("test/spex/968_backups/criterion_8014_spex.exs")])

    assert text =~ @notice

    assert text =~ "Not a regression here",
           "the footer previously asserted the opposite, and the assertion is what " <>
             "sent an agent looking for an edit that does not exist"

    assert text =~ "run from the checkout that has it",
           "an agent told only 'fix or park' has no third option, and parking is " <>
             "changing someone else's story to unblock itself"
  end

  # Counted rather than all-or-nothing, unlike the killed-process notice. A
  # killed process says nothing about which finding it replaced, so a mixed
  # group there is a run that mostly worked. An unmet precondition is
  # identifiable per finding, so the count is safe and more useful than a
  # verdict on the whole group.
  test "beside a real failure it names how many, and does not excuse the rest" do
    text =
      render([
        blocked("test/spex/968_backups/criterion_8014_spex.exs"),
        real("test/spex/992_images/criterion_8233_spex.exs")
      ])

    assert text =~ "1 of 2 never reached an assertion",
           "calling the whole group environmental would hide the genuine failure"
  end

  test "a group with no precondition failures says nothing about preconditions" do
    refute render([real("test/spex/992_images/criterion_8233_spex.exs")]) =~ @notice
  end

  # The claim the old wording made unconditionally. It is still the usual case
  # and still said — what changed is that it is no longer asserted as the only
  # one.
  test "the latch explanation no longer asserts a regression outright" do
    text =
      ProblemRenderer.render_stop_response(
        [blocked("test/spex/968_backups/criterion_8014_spex.exs")],
        [],
        session_paths: MapSet.new(["test/spex/other/criterion_1_spex.exs"])
      )

    assert text =~ "A red spex blocks even in a file this session did not touch",
           "the latch paragraph has to be present for this assertion to mean anything"

    refute text =~ "which is a regression in this working copy",
           "the analyzer cannot tell a regression from an unmet precondition, so it " <>
             "must not assert one"
  end
end
