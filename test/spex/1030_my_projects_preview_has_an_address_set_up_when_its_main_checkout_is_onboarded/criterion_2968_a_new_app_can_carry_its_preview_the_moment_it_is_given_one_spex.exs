defmodule CodeMySpecSpex.Story1030.Criterion2968Spex do
  @moduledoc """
  Story 1030 — My project's preview has an address, set up when its main checkout
  is onboarded.
  Criterion 2968 — A new app can carry its preview the moment it is given one.

  Rule: A generated application ships able to run its preview tunnel, and runs
  nothing until it is given one.

  Both halves matter and they pull against each other.

  Shipping the tunnel in the generated app is what makes the preview arrive
  without anyone editing source afterwards — the founder is non-technical, and
  "add this child spec to your supervision tree" is not a step they can take.
  So `cms.new` puts it there.

  But most generated apps are run long before they are ever previewed, and an
  app that refused to start — or sat retrying a connection to a tunnel that does
  not exist — because a preview had not been provisioned would be broken for the
  ordinary case in order to be ready for the rare one. So it starts, silently,
  doing nothing.

  ## The surface is the generated project on disk

  What `cms.new` writes is the contract. The child spec has to be present and it
  has to be inert without credentials, and both are properties of the generated
  source rather than of anything running.

  ## Red for a reason worth stating

  `mix cms.new` is not in this repository — it is the phx.new fork, still its own
  initiative. This spec is written against it anyway rather than against some
  function that does exist here, because the scenario says "an application
  generated by cms.new" and that is the contract the criterion is about.
  Inventing a local API to have something green would make the generated app's
  actual template unowned by any spec, which is the one thing this criterion
  exists to prevent.
  """

  use CodeMySpecSpex.Case

  alias CodeMySpec.Environments

  setup :register_log_in_setup_account
  setup :setup_active_project

  spex "A generated app is ready to carry a preview and does not need one" do
    scenario "A new app can carry its preview the moment it is given one" do
      given_ "a project ready to be generated", context do
        :ok = Environments.register(context.project.id, context.environment)

        {:ok, context}
      end

      when_ "the application is generated", context do
        Mix.Task.reenable("cms.new")

        result =
          Mix.Task.run("cms.new", [
            context.project.module_name |> Macro.underscore(),
            "--project",
            context.project.id
          ])

        {:ok, Map.put(context, :generated, result)}
      end

      then_ "its supervision tree can run a preview tunnel", context do
        {:ok, application} = read_application(context)

        assert application =~ "CloudflareTunnel",
               "the generated app has no preview tunnel in its supervision tree, so " <>
                 "a provisioned preview never reaches it. The remedy would be editing " <>
                 "the app's source, which is not a step the founder this is for can " <>
                 "take. Got: #{application}"

        {:ok, context}
      end

      then_ "it runs nothing until it is given one", context do
        {:ok, application} = read_application(context)

        assert application =~ "enabled:",
               "the tunnel is unconditional. Most generated apps are run long " <>
                 "before they are previewed, and one that dials a tunnel that does " <>
                 "not exist is broken for the ordinary case to be ready for the rare " <>
                 "one. Got: #{application}"

        {:ok, context}
      end
    end
  end

  # Through `Environments`, because the generated project is a set of files and
  # the in-memory environment is what sees them.
  defp read_application(context) do
    Environments.read_file(
      context.environment,
      "lib/#{context.project.module_name |> Macro.underscore()}/application.ex"
    )
  end
end
