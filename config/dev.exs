# Previews resolve through the same tunnel that serves dev.codemyspec.com, so
# a preview address works from a phone or a colleague's browser rather than
# only from this machine. The record is a CNAME to the tunnel, written once
# per project the first time its preview is asked for.
# `preview-<id>.localhost` rather than the real domain, because every label
# under `.localhost` resolves to 127.0.0.1 without a hosts entry, a tunnel or a
# DNS record — so a preview works on a laptop today rather than after the edge
# routing in c84edde5 lands. Production keeps the real domain, where the
# same-site property is the point.
#
# `target` stays as it is: it is only read by `ensure/2`, which writes a
# Cloudflare record and has no business running against a dev machine.
# Bare metal, not Docker — see `CodeMySpec.Workspaces.Runner.Local`'s
# moduledoc for what that trades away (each instance's own filesystem and
# loopback) against what it does not need (a Docker daemon on this machine).
# `host.docker.internal`, not localhost: inside a container localhost is the
# container. An instance told to report to localhost:4000 announces itself to
# its own Phoenix app, and the working copy the visitor is waiting to see never
# appears.
config :code_my_spec, CodeMySpec.Workspaces,
  runner: CodeMySpec.Workspaces.Runner.Local,
  server_url: "http://host.docker.internal:4000"

# `codemyspec.com`, not `astralbi.com`, and the reason is the session cookie.
#
# A preview is shown in a frame on the app. Served from a different registrable
# domain that frame is cross-site, and a browser does not send a `SameSite=Lax`
# cookie into one — which every generated Phoenix app sets by default. The
# framed app is then session-less on every request: its login page renders, sets
# a cookie that never comes back, and redirects to itself forever. Observed on
# Broken Oaths 2026-08-27, and `PreviewAddress`'s own moduledoc had said so all
# along.
#
# Production was always same-site: `base_domain` defaults to `codemyspec.com`
# and prod does not override it. Only dev differed, so the whole class was
# invisible until a real app was framed here.
#
# What this gives up, recorded because it was deliberate: previews were moved to
# `astralbi.com` to keep a wildcard off the production domain, and so that a
# malformed hostname in a generated tunnel config could not take
# `dev.codemyspec.com` down with it — which had happened once. That protection
# is real and this trades it for a preview that can hold a session, on the
# grounds that a preview nobody can log into is not a preview.
#
# One label deep, still: `preview-{id}.codemyspec.com` is covered by a free
# wildcard certificate and `preview-{id}.dev.codemyspec.com` would need a paid
# one.
config :code_my_spec, CodeMySpec.Workspaces.PreviewAddress,
  base_domain: "codemyspec.com",
  target: "12a798a4-81a3-4242-8b59-ac171c0a01a1.cfargotunnel.com",
  scheme: "https",
  # No `zone_id` here: `config/runtime.exs` runs after this file and sets it, so
  # a value here is overwritten and only looks like it is in force.
  manage_dns: true

# Who may frame a preview, handed to each app with its tunnel credentials so it
# never has to be told separately. The app asserts it itself —
# `ClientUtils.PreviewFraming` — because nothing sits in a tunnel's path to
# rewrite a header on the way back.
#
# `dev.codemyspec.com` only, and `http://localhost:4000` deliberately not.
# Localhost is a different registrable domain from the preview's, so a frame
# opened from there is cross-site: it renders, and then the app inside it cannot
# hold a session, because no browser sends a SameSite=Lax cookie into a
# cross-site frame. Every generated app sets Lax.
#
# Allowing it looked friendlier and was worse. A refused origin shows an empty
# pane, which is diagnosable in seconds; an allowed one shows a login page
# looping forever, which reads as the framed app being broken and cost an
# afternoon on Broken Oaths.
#
# So dev previews are opened from dev.codemyspec.com. `PreviewSameSiteTest`
# fails if this list ever gains an origin that cannot hold a session.
config :code_my_spec, CodeMySpec.Workspaces.PreviewTunnel, embedder: "https://dev.codemyspec.com"

# How long promotion's gate waits for the analyzer sweep it triggered.
#
# The default is two minutes, which is right for a machine running one project
# and wrong for this one. Measured 2026-09-12: five to eight concurrent
# `mix test` / `mix spex` runs across the worktrees on this box, load averages
# 30–54 sustained for over half an hour, and a full sweep well past two minutes.
#
# What that produced is worse than slow. `gate/1` enqueues the stale sources and
# `certify_clean/2` waits on `Analysis.await_all`; when the wait lapses the agent
# is told "the sweep is still running — promote again shortly". The obvious
# reading is to go and produce a fresh sweep, and each one an agent starts is
# another run the next gate must wait out. Every promotion in that window needed
# three or four attempts, none of them because anything was wrong with the tree.
#
# Ten minutes matches `Analysis.await_all`'s own default, so the gate stops
# being the tighter of the two clocks. It does not make promotion slower — it
# stops it giving up on work already in flight.
config :code_my_spec, :promotion_sweep_timeout, to_timeout(minute: 10)
